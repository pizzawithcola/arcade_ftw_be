"""Players and their scores, as data the operator can correct.

Login creates players and the games will write scores, but during a live show
someone always needs to fix a name, re-seat a device in a room, or hand out
points when a game misbehaved. Those are the endpoints here.

Scores belong to the player: `scores.player_id` is a foreign key with
ON DELETE CASCADE and no separate identity, so deleting a player deletes their
score with them. There is nothing to clean up in code, and no way for a score to
outlive its owner.
"""

from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, Response
from pydantic import BaseModel, Field
from sqlalchemy import func, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.auth import Claims, require_admin, require_display
from app.database import get_session
from app.events import EVENT_KEYS
from app.models import Player, Room, Score

router = APIRouter(prefix="/players", tags=["players"])

# Points are small integers in the games; the bound only exists to reject a
# pasted-in negative or a typo like 100000 instead of 100.
_SCORE_LIMIT = 100_000

SCORE_FIELDS = ("hallucination_score", "data_score", "sabotage_score", "ultimate_score")


class PlayerPatch(BaseModel):
    nickname: str | None = Field(default=None, min_length=1, max_length=64)
    event: str | None = None
    # Explicit null takes the player out of their room; omitting the field leaves
    # them where they are. That distinction is why this is not just `or`.
    room_code: str | None = None


class ScoreSet(BaseModel):
    hallucination_score: int | None = Field(default=None, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)
    data_score: int | None = Field(default=None, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)
    sabotage_score: int | None = Field(default=None, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)
    ultimate_score: int | None = Field(default=None, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)


class ScoreAdjust(BaseModel):
    """Increments, not totals - a game reporting "you earned 20 points"."""

    hallucination_score: int = Field(default=0, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)
    data_score: int = Field(default=0, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)
    sabotage_score: int = Field(default=0, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)
    ultimate_score: int = Field(default=0, ge=-_SCORE_LIMIT, le=_SCORE_LIMIT)


async def _player_or_404(player_id: int, session: AsyncSession) -> Player:
    player = await session.get(Player, player_id)
    if player is None:
        raise HTTPException(status_code=404, detail=f"unknown player: {player_id}")
    return player


def _score_body(player_id: int, score: Score | None) -> dict | None:
    if score is None:
        return None
    return {
        "player_id": player_id,
        **{field: getattr(score, field) for field in SCORE_FIELDS},
        # Generated by the database, so it is read back rather than computed.
        "total_score": score.total_score,
    }


def _player_body(player: Player, score: Score | None) -> dict:
    return {
        "player_id": player.id,
        "nickname": player.nickname,
        "event": player.event,
        "room_code": player.room_code,
        "created_at": player.created_at,
        "total_score": score.total_score if score is not None else 0,
        "score": _score_body(player.id, score),
    }


@router.get("", summary="Search players")
async def list_players(
    room: str | None = None,
    event: str | None = None,
    _: Claims = Depends(require_display),
    session: AsyncSession = Depends(get_session),
) -> dict:
    """Flat list with totals, for finding the id behind a name on the floor."""
    query = (
        select(Player, Score)
        .outerjoin(Score, Score.player_id == Player.id)
        .order_by(func.coalesce(Score.total_score, 0).desc(), Player.id)
    )
    if room is not None:
        query = query.where(Player.room_code == room)
    if event is not None:
        query = query.where(Player.event == event)
    rows = (await session.execute(query)).all()
    return {"players": [_player_body(player, score) for player, score in rows]}


@router.get("/{player_id}", summary="One player with their score")
async def get_player(
    player_id: int,
    _: Claims = Depends(require_display),
    session: AsyncSession = Depends(get_session),
) -> dict:
    player = await _player_or_404(player_id, session)
    return _player_body(player, await session.get(Score, player_id))


@router.patch("/{player_id}", summary="Rename, re-event or move a player")
async def patch_player(
    player_id: int,
    body: PlayerPatch,
    _: Claims = Depends(require_admin),
    session: AsyncSession = Depends(get_session),
) -> dict:
    player = await _player_or_404(player_id, session)
    given = body.model_fields_set

    if "event" in given and body.event is not None:
        if body.event not in EVENT_KEYS:
            raise HTTPException(status_code=422, detail=f"unknown event: {body.event}")
        player.event = body.event

    if "nickname" in given and body.nickname is not None:
        nickname = body.nickname.strip()
        if not nickname:
            raise HTTPException(status_code=422, detail="nickname required")
        player.nickname = nickname

    if "room_code" in given:
        if body.room_code is not None and await session.get(Room, body.room_code) is None:
            raise HTTPException(status_code=404, detail=f"unknown room: {body.room_code}")
        player.room_code = body.room_code

    try:
        await session.commit()
    except IntegrityError as exc:
        # (event, nickname) is unique, so a rename can collide with someone else.
        raise HTTPException(status_code=409, detail="that nickname is taken") from exc
    await session.refresh(player)
    return _player_body(player, await session.get(Score, player_id))


@router.delete("/{player_id}", status_code=204, summary="Delete a player and their score")
async def delete_player(
    player_id: int,
    _: Claims = Depends(require_admin),
    session: AsyncSession = Depends(get_session),
) -> Response:
    player = await _player_or_404(player_id, session)
    await session.delete(player)
    await session.commit()
    return Response(status_code=204)


@router.put("/{player_id}/score", summary="Set score components")
async def set_score(
    player_id: int,
    body: ScoreSet,
    _: Claims = Depends(require_admin),
    session: AsyncSession = Depends(get_session),
) -> dict:
    """Absolute values; components left out keep whatever they had.

    The first write creates the row, so a player never needs a separate "start
    scoring" step. `total_score` is a generated column and is not accepted here -
    it is the sum of these four by construction.
    """
    await _player_or_404(player_id, session)
    score = await session.get(Score, player_id)
    if score is None:
        score = Score(player_id=player_id)
        session.add(score)
    for field in body.model_fields_set & set(SCORE_FIELDS):
        setattr(score, field, getattr(body, field))
    await session.commit()
    # Refresh to read back the recomputed generated column.
    await session.refresh(score)
    return _score_body(player_id, score)


@router.post("/{player_id}/score/adjust", summary="Add points to score components")
async def adjust_score(
    player_id: int,
    body: ScoreAdjust,
    _: Claims = Depends(require_admin),
    session: AsyncSession = Depends(get_session),
) -> dict:
    """Deltas, including negatives - a game awarding or deducting as it reports."""
    await _player_or_404(player_id, session)
    score = await session.get(Score, player_id)
    if score is None:
        score = Score(player_id=player_id)
        session.add(score)
    for field in SCORE_FIELDS:
        delta = getattr(body, field)
        if delta:
            # Unset components are still None until the INSERT applies the column
            # default, so a brand-new row starts from zero rather than blowing up.
            setattr(score, field, (getattr(score, field) or 0) + delta)
    await session.commit()
    await session.refresh(score)
    return _score_body(player_id, score)
